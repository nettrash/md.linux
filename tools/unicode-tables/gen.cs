// Generates crates/md-core/src/text/unicode_tables.rs from .NET's own Unicode data.
//
// md.win is the reference this port is written against, and its behaviour on a scalar is
// whatever .NET answers: Rune.GetUnicodeCategory, Rune.ToUpperInvariant, Rune.ToLowerInvariant.
// Rust's std has no general categories and maps case with the FULL mappings, so the tables
// are dumped from .NET rather than built from a UnicodeData.txt of some other version.
//
//   dotnet run tools/unicode-tables/gen.cs > crates/md-core/src/text/unicode_tables.rs
//
// Needs the .NET 10 SDK. The output is committed; the build never runs this.

using System.Globalization;
using System.Text;

var output = new StringBuilder();
output.AppendLine("// @generated by tools/unicode-tables/gen.cs from .NET " + Environment.Version + " — do not edit.");
output.AppendLine("// General categories (ranges of equal category, unassigned omitted) and the simple case");
output.AppendLine("// mappings (Rune.ToUpperInvariant / Rune.ToLowerInvariant) where they differ from identity, and\n// the upper half of Windows-1251.");
output.AppendLine();

// Ranges of one category, Cn (unassigned) and surrogates left out.
output.AppendLine("pub(crate) static CATEGORY_RANGES: &[(u32, u32, u8)] = &[");
int? start = null;
var current = UnicodeCategory.OtherNotAssigned;
void Flush(int end)
{
    if (start is int s && current != UnicodeCategory.OtherNotAssigned)
        output.AppendLine($"    (0x{s:X4}, 0x{end:X4}, {(int)current}),");
}
for (var cp = 0; cp <= 0x10FFFF; cp++)
{
    UnicodeCategory category;
    if (cp is >= 0xD800 and <= 0xDFFF) category = UnicodeCategory.OtherNotAssigned;
    else category = Rune.GetUnicodeCategory(new Rune(cp));
    if (start is null) { start = cp; current = category; continue; }
    if (category != current)
    {
        Flush(cp - 1);
        start = cp;
        current = category;
    }
}
Flush(0x10FFFF);
output.AppendLine("];");
output.AppendLine();

void Mapping(string name, Func<Rune, Rune> map)
{
    output.AppendLine($"pub(crate) static {name}: &[(u32, u32)] = &[");
    for (var cp = 0; cp <= 0x10FFFF; cp++)
    {
        if (cp is >= 0xD800 and <= 0xDFFF) continue;
        var rune = new Rune(cp);
        var mapped = map(rune).Value;
        if (mapped != cp) output.AppendLine($"    (0x{cp:X4}, 0x{mapped:X4}),");
    }
    output.AppendLine("];");
    output.AppendLine();
}
Mapping("SIMPLE_UPPER", Rune.ToUpperInvariant);
Mapping("SIMPLE_LOWER", Rune.ToLowerInvariant);

// Windows-1251, bytes 0x80-0xFF, as .NET's code-pages provider decodes them. 0x98 is the one byte
// the code page leaves undefined (Foundation refuses it; .NET maps it to U+0098, so md.win
// refuses it by hand) and is written as 0 here.
Encoding.RegisterProvider(CodePagesEncodingProvider.Instance);
var cp1251 = Encoding.GetEncoding(1251);
output.AppendLine("pub(crate) static CP1251_HIGH: [u16; 128] = [");
for (var row = 0x80; row <= 0xFF; row += 8)
{
    var cells = new List<string>();
    for (var b = row; b < row + 8; b++)
    {
        var decoded = b == 0x98 ? 0 : cp1251.GetString(new[] { (byte)b })[0];
        cells.Add($"0x{(int)decoded:X4}");
    }
    output.AppendLine("    " + string.Join(", ", cells) + ",");
}
output.AppendLine("];");

Console.Out.Write(output.ToString().TrimEnd() + "\n");
